export type StringKey = keyof typeof STRINGS.en;

export function t(lang: Lang, key: StringKey): string {
  return (STRINGS[lang][key] as string) ?? STRINGS.en[key];
}

export function loadLang(): Lang {
  try {
    const v = localStorage.getItem("musd-pocket-lang");
    if (v === "en" || v === "es" || v === "pt" || v === "zh" || v === "fr") return v;
  } catch { /* ignore */ }
  return "en";
}

export function saveLang(lang: Lang) {
  try { localStorage.setItem("musd-pocket-lang", lang); } catch { /* ignore */ }
}

export function cycleLang(current: Lang): Lang {
  const ids = LANG_META.map((m) => m.id);
  const i = ids.indexOf(current);
  return ids[(i + 1) % ids.length];
}
